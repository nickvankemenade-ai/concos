"""Rotate and scale generated latents: does direction carry class and magnitude carry the instance?

    python rotate_scale.py                           # Euclidean-only vs ConCoS-only flat VAEs
    python rotate_scale.py --models plain concos concosonly

For a latent z generated by the class-conditional LDM for class A, with class mean directions c_A, c_B
(means of unit-normalised training latents), decode

    z(f, gamma) = gamma * R(f*phi) z

where R(theta) rotates by theta in the plane spanned by c_A and c_B (the rotation that maps c_A onto c_B when
theta = phi = angle(c_A, c_B)) and leaves every direction orthogonal to that plane alone. So the length of z
and its instance-specific part are kept; f = 0 is z itself and f = 1 has moved its class component
from A to B. gamma scales the length. Everything happens around the origin of the VAE's raw latent space.

Outputs (outputs/flat/rotate_scale/):
  grid.png      for a few class pairs: rows = rotation f, columns = scale gamma, one block per model
  metrics.png   classifier on decoded images, over every ordered class pair (A -> B):
                P(target class) vs f, P(class unchanged) vs gamma, LPIPS change vs gamma
  metrics.json
"""

import argparse
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import torch
import torch.nn.functional as F
from torchvision.utils import make_grid

from concos_ldm import flat
from concos_ldm.common import CLASSES, DEFAULT_OUT, DEFAULT_WORK, NUM_CLASSES, get_device
from concos_ldm.metrics import classify, get_classifier

FRACS = [0.0, 0.25, 0.5, 0.75, 1.0]
GAMMAS = [0.5, 0.75, 1.0, 1.5, 2.0]
PAIRS = [(1, 7), (3, 5), (8, 6)]          # automobile -> horse, cat -> dog, ship -> frog
NAMES = {"plain": "Euclidean-only VAE", "concosonly": "ConCoS-only VAE", "concos": "ConCoS + Euclidean VAE"}
COLORS = {"plain": "#2a78d6", "concosonly": "#eb6834", "concos": "#1baf7a"}
SURFACE, INK, MUTED, GRID = "#fbfbf8", "#1f1f1f", "#555555", "#e6e5e0"


def class_directions(lat):
    h = len(lat["mu"]) // 2
    u = F.normalize(lat["mu"][:h], dim=1)
    y = lat["y"][:h]
    return F.normalize(torch.stack([u[y == k].mean(0) for k in range(NUM_CLASSES)]), dim=1)


def rotate_scale(z, src_dir, tgt_dir, frac, gamma):
    """Rotate z (N, D) by frac of the angle from src_dir to tgt_dir (unit, (N, D)) in their plane; scale by gamma."""
    e1 = src_dir
    cos_phi = (e1 * tgt_dir).sum(1, keepdim=True).clamp(-1, 1)
    e2 = F.normalize(tgt_dir - cos_phi * e1, dim=1)
    th = frac * torch.arccos(cos_phi)
    x1, x2 = (z * e1).sum(1, keepdim=True), (z * e2).sum(1, keepdim=True)
    rest = z - x1 * e1 - x2 * e2
    zr = rest + (x1 * torch.cos(th) - x2 * torch.sin(th)) * e1 + (x1 * torch.sin(th) + x2 * torch.cos(th)) * e2
    return gamma * zr


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--work", default=DEFAULT_WORK)
    p.add_argument("--out", default=os.path.join(DEFAULT_OUT, "flat", "rotate_scale"))
    p.add_argument("--models", nargs="+", default=["plain", "concosonly"])
    p.add_argument("--per-class", type=int, default=10, help="generated latents per source class for metrics")
    p.add_argument("--guidance", type=float, default=3.0)
    p.add_argument("--seed", type=int, default=0)
    args = p.parse_args()
    os.makedirs(args.out, exist_ok=True)
    dev = get_device()
    import lpips
    perc = lpips.LPIPS(net="vgg", verbose=False).to(dev).eval()
    clf = get_classifier(args.work)

    metrics, grids = {}, {}
    for m in args.models:
        s = flat.FlatSampler(args.work, m, cond=True, device=dev)
        dirs = class_directions(flat.load_latents(args.work, m, dev))
        src = torch.arange(NUM_CLASSES).repeat_interleave(args.per_class)
        _, z = s.sample(labels=src, guidance=args.guidance, seed=args.seed)
        src = src.to(dev)
        zi, tgt = [], []
        for b in range(NUM_CLASSES):
            keep = src != b
            zi.append(z[keep])
            tgt.append(torch.full((int(keep.sum()),), b, device=dev))
        zi, tgt = torch.cat(zi), torch.cat(tgt)
        srci = torch.cat([src[src != b] for b in range(NUM_CLASSES)])
        res = {"p_target_vs_frac": {}, "p_source_vs_frac": {}, "p_unchanged_vs_gamma": {}, "lpips_vs_gamma": {}}
        for f in FRACS:
            pred = classify(clf, s.decode(rotate_scale(zi, dirs[srci], dirs[tgt], f, 1.0))).to(dev)
            res["p_target_vs_frac"][str(f)] = float((pred == tgt).float().mean())
            res["p_source_vs_frac"][str(f)] = float((pred == srci).float().mean())
        base_img = s.decode(z)
        base = classify(clf, base_img)
        for g in GAMMAS:
            img = s.decode(g * z)
            res["p_unchanged_vs_gamma"][str(g)] = float((classify(clf, img) == base).float().mean())
            with torch.no_grad():
                res["lpips_vs_gamma"][str(g)] = float(perc(img.to(dev) * 2 - 1, base_img.to(dev) * 2 - 1).mean())
        res["base_class_acc"] = float((base.to(dev) == src).float().mean())
        res["mean_class_angle_deg"] = float(torch.rad2deg(torch.arccos((dirs[srci] * dirs[tgt]).sum(1).clamp(-1, 1))).mean())
        res["mean_cos_z_to_own_class"] = float((F.normalize(z, dim=1) * dirs[src]).sum(1).mean())
        metrics[m] = res
        print(f"{m}: " + json.dumps({k: v for k, v in res.items()}), flush=True)

        blocks = []
        for a, b in PAIRS:
            za = z[(src == a).nonzero()[0]].expand(1, -1)
            cells = [rotate_scale(za, dirs[a][None], dirs[b][None], f, g) for f in FRACS for g in GAMMAS]
            blocks.append(make_grid(s.decode(torch.cat(cells)), nrow=len(GAMMAS), padding=1, pad_value=1.0))
        grids[m] = blocks
        del s
        torch.cuda.empty_cache()

    with open(os.path.join(args.out, "metrics.json"), "w") as fh:
        json.dump({"fracs": FRACS, "gammas": GAMMAS, "guidance": args.guidance, **metrics}, fh, indent=2)

    fig, axes = plt.subplots(len(PAIRS), len(args.models), figsize=(5.2 * len(args.models), 5.6 * len(PAIRS)),
                             squeeze=False, facecolor=SURFACE)
    for c, m in enumerate(args.models):
        for r, (a, b) in enumerate(PAIRS):
            ax = axes[r, c]
            gimg = grids[m][r]
            ax.imshow(gimg.permute(1, 2, 0).numpy(), interpolation="nearest")
            hh, ww = gimg.shape[1] / len(FRACS), gimg.shape[2] / len(GAMMAS)
            ax.set_yticks([hh * (k + 0.5) for k in range(len(FRACS))],
                          [f"{int(f * 100)}%" for f in FRACS], fontsize=9, color=MUTED)
            ax.set_xticks([ww * (k + 0.5) for k in range(len(GAMMAS))], [f"γ={g:g}" for g in GAMMAS],
                          fontsize=9, color=MUTED)
            ax.tick_params(length=0)
            for sp in ax.spines.values():
                sp.set_visible(False)
            ax.set_ylabel(f"rotation {CLASSES[a]} → {CLASSES[b]}", color=MUTED, fontsize=10)
            ax.set_title(f"{NAMES.get(m, m)}" if r == 0 else "", loc="left", fontsize=13, color=INK)
    fig.suptitle("Rotating (rows) and scaling (columns) a generated latent", fontsize=15, color=INK,
                 x=0.01, ha="left")
    fig.tight_layout(rect=(0, 0, 1, 0.97))
    fig.savefig(os.path.join(args.out, "grid.png"), dpi=150, facecolor=SURFACE)
    plt.close(fig)

    fig, axes = plt.subplots(1, 3, figsize=(15, 4.3), facecolor=SURFACE)
    spec = [("p_target_vs_frac", FRACS, "rotation f (fraction of the angle to class B)", "P(classified as B) ↑",
             "Rotation switches the class"),
            ("p_unchanged_vs_gamma", GAMMAS, "γ", "P(class unchanged) ↑", "Scaling keeps the class"),
            ("lpips_vs_gamma", GAMMAS, "γ", "LPIPS to γ = 1", "How much scaling changes the image")]
    for ax, (k, xs, xl, yl, title) in zip(axes, spec):
        ax.set_facecolor(SURFACE)
        ax.grid(color=GRID, lw=0.7)
        ax.set_axisbelow(True)
        ax.tick_params(colors=MUTED, labelsize=9, length=0)
        for sp in ax.spines.values():
            sp.set_visible(False)
        for m in args.models:
            ys = [metrics[m][k][str(x)] for x in xs]
            ax.plot(xs, ys, "-o", color=COLORS.get(m, "#6250d6"), lw=2, ms=7, mec=SURFACE, mew=2,
                    label=NAMES.get(m, m))
            if k == "p_target_vs_frac":
                ys2 = [metrics[m]["p_source_vs_frac"][str(x)] for x in xs]
                ax.plot(xs, ys2, "--", color=COLORS.get(m, "#6250d6"), lw=1.3, alpha=0.8)
        ax.set_xlabel(xl, color=MUTED)
        ax.set_ylabel(yl, color=MUTED)
        ax.set_title(title, loc="left", fontsize=12, color=INK)
    axes[0].text(0.02, 0.02, "dashed: P(still classified as A)", transform=axes[0].transAxes, fontsize=8, color=MUTED)
    axes[0].legend(frameon=False, fontsize=9, labelcolor=INK)
    fig.tight_layout()
    fig.savefig(os.path.join(args.out, "metrics.png"), dpi=160, facecolor=SURFACE)
    plt.close(fig)
    print("wrote", args.out)


if __name__ == "__main__":
    main()
